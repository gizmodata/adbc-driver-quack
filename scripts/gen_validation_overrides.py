"""Generate validation/queries/type/bind/*.txtcase DuckDB overrides from the
base cases of the installed adbc-drivers-validation package.

Each override holds only the parts that differ from the base case (the
suite merges per part) plus a metadata caveat saying why. Run after
bumping the pinned suite version:

    python scripts/gen_validation_overrides.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import adbc_drivers_validation

BASE = Path(adbc_drivers_validation.__file__).parent / "queries" / "type" / "bind"
OUT = Path(__file__).resolve().parent.parent / "validation" / "queries" / "type" / "bind"
INT64_MIN, INT64_MAX = -(2**63), 2**63 - 1

HEADER = """// Copyright (c) 2026 GizmoData LLC
// SPDX-License-Identifier: MIT
//
// DuckDB-specific override of the adbc-drivers-validation base case of the
// same name (Apache-2.0). Generated by scripts/gen_validation_overrides.py.
"""


def parts(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    name = None
    for line in path.read_text().splitlines():
        m = re.match(r"^// part: (\w+)\s*$", line)
        if m:
            name = m.group(1)
            out[name] = ""
        elif name:
            out[name] += line + "\n"
    return {k: v.strip() + "\n" for k, v in out.items()}


def rows(text: str) -> list[dict]:
    return [json.loads(line) for line in text.splitlines() if line.strip()]


def dump(rs: list[dict]) -> str:
    return "\n".join(json.dumps(r) for r in rs) + "\n"


def write(name: str, caveat: str, **new_parts: str) -> None:
    body = HEADER + "\n// part: metadata\n\n[tags]\ncaveats = [" + json.dumps(caveat) + "]\n"
    for part, text in new_parts.items():
        body += f"\n// part: {part}\n\n{text}"
    (OUT / f"{name}.txtcase").write_text(body)


def rescale(name: str, fmt_from: str, fmt_to: str, factor: int, caveat: str) -> None:
    p = parts(BASE / f"{name}.txtcase")
    schema = p["expected_schema"].replace(f'"{fmt_from}', f'"{fmt_to}')
    expected = [
        {k: (v * factor if isinstance(v, int) and k != "idx" else v) for k, v in r.items()}
        for r in rows(p["expected"])
    ]
    write(name, caveat, expected_schema=schema, expected=dump(expected))


def drop_infinity(name: str, caveat: str) -> None:
    p = parts(BASE / f"{name}.txtcase")

    def finite(r: dict) -> bool:
        return all(v not in (INT64_MIN, INT64_MAX) for k, v in r.items() if k != "idx")

    write(
        name,
        caveat,
        bind=dump([r for r in rows(p["bind"]) if finite(r)]),
        expected=dump([r for r in rows(p["expected"]) if finite(r)]),
    )


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    us = "DuckDB stores TIME at microsecond precision (TIME_NS for nanoseconds), so TIME(p) reads back as time64[us]."
    rescale("time_s", "tts", "ttu", 1_000_000, us)
    rescale("time_ms", "ttm", "ttu", 1_000, us)
    p = parts(BASE / "time_ns.txtcase")
    write(
        "time_ns",
        "DuckDB's TIME(9) is microsecond TIME; its nanosecond type is TIME_NS.",
        setup_query=re.sub(r"TIME\(9\)", "TIME_NS", p["setup_query"]),
    )
    tz = "DuckDB's TIMESTAMPTZ is microsecond precision (TIMESTAMPTZ_NS for nanoseconds)."
    rescale("timestamptz_s", "tss:", "tsu:", 1_000_000, tz)
    rescale("timestamptz_ms", "tsm:", "tsu:", 1_000, tz)
    inf = "DuckDB reserves the INT64 extremes of TIMESTAMP_NS as -infinity/infinity, so they are not bindable values."
    drop_infinity("timestamp_ns", inf)
    p = parts(BASE / "timestamptz_ns.txtcase")

    def finite(r: dict) -> bool:
        return all(v not in (INT64_MIN, INT64_MAX) for k, v in r.items() if k != "idx")

    write(
        "timestamptz_ns",
        inf + " DuckDB's TIMESTAMP(9) WITH TIME ZONE is microsecond TIMESTAMPTZ; its nanosecond type is TIMESTAMPTZ_NS.",
        setup_query=re.sub(r"TIMESTAMP\(9\) WITH TIME ZONE", "TIMESTAMPTZ_NS", p["setup_query"]),
        bind=dump([r for r in rows(p["bind"]) if finite(r)]),
        expected=dump([r for r in rows(p["expected"]) if finite(r)]),
    )
    for name in ("binary", "binary_view", "large_binary", "fixed_size_binary"):
        p = parts(BASE / f"{name}.txtcase")
        write(
            name,
            "DuckDB's binary type is BLOB, which takes no length.",
            setup_query=re.sub(r"VARBINARY\(\d+\)|BINARY\(\d+\)|BLOB\(\d+\)|VARBINARY", "BLOB", p["setup_query"]),
        )


if __name__ == "__main__":
    main()
